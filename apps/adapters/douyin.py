"""抖音（Douyin）适配器。

基于 yt-dlp 内置的 Douyin extractor（无需自建解析器，遵循「复用开源能力」原则）。
- 探测 / 下载均走 yt-dlp（参数数组调用，不拼 shell）
- 支持 Cookie（可选，部分视频/高清需要登录态），Cookie 仅写入受控临时目录
- 抖音一般无平台字幕，字幕走本地 ASR（由入库管线处理）
"""
from __future__ import annotations

import json
import re
import time
import urllib.parse
from pathlib import Path

from apps.adapters._util import ffprobe_json, run_cmd, sha256_file
from apps.adapters.base import AcquireError, ErrorCode, FetchOpts, MediaResult, VideoMeta

DOUYIN_HOST_RE = re.compile(r"(v\.douyin\.com|www\.douyin\.com|douyin\.com)/", re.I)
_SHARE_URL_RE = re.compile(r"https?://[^\s\"'<>]+")


def _safe_unlink(p: Path | None, attempts: int = 15) -> None:
    if not p:
        return
    for _ in range(attempts):
        try:
            if Path(p).exists():
                Path(p).unlink()
            return
        except (PermissionError, OSError):
            time.sleep(0.2)


def normalize_douyin_url(source: str) -> str:
    """从分享文案中提取链接（抖音分享常带一段文字 + 短链）。"""
    s = (source or "").strip()
    if not _SHARE_URL_RE.search(s):
        return s
    m = _SHARE_URL_RE.search(s)
    return m.group(0) if m else s


class DouyinAdapter:
    name = "douyin"

    def __init__(self, yt_dlp_path: str = "yt-dlp", ffprobe: str = "ffprobe",
                 cookie_provider=None, cookie_tmp_dir=None, cookies_from_browser: str = ""):
        self._ytdlp = yt_dlp_path
        self._ffprobe = ffprobe
        self._cookies = cookie_provider
        self._from_browser = (cookies_from_browser or "").strip()
        if cookie_tmp_dir:
            self._cookie_dir = Path(cookie_tmp_dir)
        else:
            _root = Path(__file__).resolve().parents[2]
            self._cookie_dir = _root / ".tmp" / "cookies"
        try:
            self._cookie_dir.mkdir(parents=True, exist_ok=True)
        except OSError:
            pass

    # ---------- 基础 ----------
    async def can_handle(self, url: str) -> bool:
        return bool(DOUYIN_HOST_RE.search(normalize_douyin_url(url)))

    def _cookie_header(self) -> str | None:
        if not self._cookies:
            return None
        try:
            c = self._cookies.get("douyin")
        except Exception:
            return None
        if not c:
            return None
        return "; ".join(f"{k}={v}" for k, v in c.items())

    def _new_cookie_file(self) -> Path:
        import uuid
        self._cookie_dir.mkdir(parents=True, exist_ok=True)
        return self._cookie_dir / f"cookie_dy_{uuid.uuid4().hex[:12]}.txt"

    def _write_cookie_file(self, path: Path) -> bool:
        ck = self._cookie_header()
        if not ck:
            return False
        lines = ["# Netscape HTTP Cookie File", "# generated by VidLearn AI"]
        for part in ck.split(";"):
            part = part.strip()
            if "=" not in part:
                continue
            k, v = part.split("=", 1)
            lines.append("\t".join([".douyin.com", "TRUE", "/", "FALSE", "0", k, v]))
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return True

    def _classify(self, err: str, out: str) -> AcquireError:
        t = ((err or "") + (out or "")).lower()
        if any(k in t for k in ("fresh cookies", "login", "cookie", "passport", "登录")):
            return AcquireError(
                ErrorCode.NEED_LOGIN,
                "抖音需要新鲜 Cookie：请在导入页粘贴浏览器 Cookie（含 ttwid、msToken 等），"
                "或在 .env 设置 VIDLEARN_YTDLP_COOKIES_FROM_BROWSER=chrome/edge/firefox 后重试",
                retryable=False)
        if any(k in t for k in ("verify", "captcha", "risk", "拒绝", "forbidden", "403")):
            return AcquireError(ErrorCode.BLOCKED, "抖音风控/需要验证：请稍后重试或更换网络", retryable=True)
        if any(k in t for k in ("not available", "removed", "deleted", "已删除", "404", "no video")):
            return AcquireError(ErrorCode.NOT_AUTHORIZED, "视频不存在或不可访问", retryable=False)
        if any(k in t for k in ("timed out", "timeout", "connection", "network", "temporary failure", "getaddrinfo")):
            return AcquireError(ErrorCode.NETWORK, "网络错误，请稍后重试", retryable=True)
        if "unsupported url" in t or "no suitable" in t:
            return AcquireError(ErrorCode.UNSUPPORTED_URL, "无法识别的抖音链接", retryable=False)
        return AcquireError(ErrorCode.INTERNAL, (err or out or "yt-dlp 失败")[:200], retryable=True)

    async def verify_login(self) -> dict:
        """抖音 Cookie 检查。

        抖音没有稳定的「登录校验」公开接口，这里做**本地合理性检查**：
        是否存在关键 Cookie（ttwid / msToken / sessionid）。返回 {ok, keys, message}。
        """
        ck = self._cookies.get("douyin") if self._cookies else None
        if not ck:
            return {"ok": False, "keys": [], "message": "未配置 Cookie"}
        keys = list(ck.keys())
        has_core = any(k in ck for k in ("ttwid", "msToken", "sessionid", "sessionid_ss"))
        if not has_core:
            return {"ok": False, "keys": keys,
                    "message": "Cookie 缺少 ttwid/msToken/sessionid 等关键字段"}
        return {"ok": True, "keys": keys, "message": "已配置（抖音无离线登录校验，导入时以实际解析为准）"}

    # ---------- 探测 ----------
    async def probe(self, url: str) -> VideoMeta:
        url = normalize_douyin_url(url)
        args = [self._ytdlp, "--simulate", "--dump-single-json", "--no-warnings", "--no-playlist"]
        tmp_cookie = None
        if self._cookie_header():
            tmp_cookie = self._new_cookie_file()
            self._write_cookie_file(tmp_cookie)
            args += ["--cookies", str(tmp_cookie)]
        elif self._from_browser:
            args += ["--cookies-from-browser", self._from_browser]
        args += ["--add-header", "Referer:https://www.douyin.com/", url]
        try:
            rc, out, err = await run_cmd(args, timeout=120)
        finally:
            _safe_unlink(tmp_cookie)
        if rc != 0:
            raise self._classify(err, out)
        try:
            d = json.loads(out)
        except json.JSONDecodeError:
            raise AcquireError(ErrorCode.FORMAT_CHANGED, "yt-dlp 输出非 JSON", retryable=True)
        fmts = d.get("formats") or []
        heights = sorted({f.get("height") for f in fmts if f.get("height")}, reverse=True)
        return VideoMeta(
            platform="douyin",
            platform_video_id=str(d.get("id") or ""),
            title=d.get("title") or d.get("description") or "抖音视频",
            author=d.get("uploader") or d.get("creator"),
            duration_ms=int((d.get("duration") or 0) * 1000),
            cover_url=d.get("thumbnail"),
            available_heights=heights,
            has_subtitle_tracks=bool(d.get("subtitles") or d.get("automatic_captions")),
            source_url=d.get("webpage_url") or url,
            extra={"extractor": d.get("extractor")},
        )

    # ---------- 下载 ----------
    async def fetch_media(self, url: str, opts: FetchOpts) -> MediaResult:
        url = normalize_douyin_url(url)
        out_dir = Path(opts.out_dir or ".")
        out_dir.mkdir(parents=True, exist_ok=True)
        outtmpl = str(out_dir / "%(id)s.%(ext)s")

        args = [self._ytdlp, "--no-warnings", "--no-playlist",
                "--merge-output-format", "mp4", "-o", outtmpl,
                "--add-header", "Referer:https://www.douyin.com/"]
        if opts.download_sections:
            args += ["--download-sections", opts.download_sections]
        if opts.audio_only:
            args += ["-f", "bestaudio/best"]
        else:
            # 抖音多为单一 mp4；优先 mp4/H.264，回退最佳
            h = f"[height<={opts.max_height}]" if opts.max_height else ""
            args += ["-f", f"bv*{h}[ext=mp4]+ba[ext=m4a]/b{ h }[ext=mp4]/bv*{h}+ba/b[ext=mp4]/best"]
        tmp_cookie = None
        if self._cookie_header():
            tmp_cookie = self._new_cookie_file()
            self._write_cookie_file(tmp_cookie)
            args += ["--cookies", str(tmp_cookie)]
        elif self._from_browser:
            args += ["--cookies-from-browser", self._from_browser]
        args.append(url)
        try:
            rc, out, err = await run_cmd(args, timeout=opts.timeout_sec)
        finally:
            _safe_unlink(tmp_cookie)
        if rc != 0:
            raise self._classify(err, out)

        files = sorted(out_dir.glob("*"), key=lambda p: p.stat().st_mtime, reverse=True)
        media = [f for f in files if f.is_file() and f.suffix.lower() in
                 (".mp4", ".mkv", ".webm", ".m4a", ".mp3", ".aac")]
        if not media:
            raise AcquireError(ErrorCode.MEDIA_INVALID, "下载完成但未找到媒体文件")
        target = media[0]

        info = await ffprobe_json(target, self._ffprobe)
        if info is None:
            raise AcquireError(ErrorCode.MEDIA_INVALID, "下载产物 FFprobe 无法解析")
        fmt = info.get("format") or {}
        streams = info.get("streams") or []
        v = [s for s in streams if s.get("codec_type") == "video"]
        a = [s for s in streams if s.get("codec_type") == "audio"]
        return MediaResult(
            file_path=target,
            container=fmt.get("format_name") or "unknown",
            sha256=sha256_file(target),
            declared_duration_ms=int(float(fmt.get("duration") or 0) * 1000),
            width=v[0].get("width") if v else None,
            height=v[0].get("height") if v else None,
            vcodec=v[0].get("codec_name") if v else None,
            acodec=a[0].get("codec_name") if a else None,
            has_audio=bool(a),
        )
